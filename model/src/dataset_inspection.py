"""Create a reproducible Markdown inspection report without changing source data."""

from __future__ import annotations

import zipfile
from pathlib import Path

import pandas as pd

from .data_preparation import DATA_DIR, URL_FILE, UCI_FILE, _mendeley_zip, load_mendeley_sms, load_phiusiil_urls, load_uci_sms


def _table(mapping: dict) -> str:
    return " | ".join(f"{key}: {value}" for key, value in mapping.items())


def build_dataset_report(destination: Path | None = None) -> Path:
    """Inspect every file below data/ and save the verified Markdown report."""
    destination = destination or DATA_DIR.parent / "DATASET_INSPECTION_REPORT.md"
    uci_raw = pd.read_csv(UCI_FILE, sep="\t", header=None, names=["label", "text"], dtype=str, encoding="utf-8")
    mendeley_raw = pd.read_csv(_mendeley_zip(), compression="zip", dtype=str, encoding="utf-8")
    url_raw = pd.read_csv(URL_FILE, encoding="utf-8-sig", low_memory=False)
    uci, mendeley, urls = load_uci_sms(), load_mendeley_sms(), load_phiusiil_urls()
    files = [path for path in DATA_DIR.rglob("*") if path.is_file()]
    lines = [
        "# ScaMail AI dataset inspection report", "",
        "Generated by `src.dataset_inspection` before training. Original files were read only; no source dataset was altered.", "",
        "## Recursive file inventory", "",
        "| File | Format / role | Encoding or archive detail |", "|---|---|---|",
    ]
    for path in files:
        relative = path.relative_to(DATA_DIR).as_posix()
        suffix = path.suffix.lower()
        if suffix == ".csv":
            detail = "UTF-8 with BOM" if path == URL_FILE else "UTF-8"
            role = "CSV"
        elif path.name == "SMSSpamCollection":
            role, detail = "tab-separated text (no header)", "UTF-8"
        elif suffix == ".zip":
            with zipfile.ZipFile(path) as archive:
                detail = "; ".join(item.filename for item in archive.infolist())
            role = "ZIP archive"
        elif suffix == ".pdf":
            role, detail = "PDF reference/visualisation", "binary PDF"
        elif suffix == ".py":
            role, detail = "Python utility/source", "UTF-8"
        else:
            role, detail = "text documentation", "UTF-8"
        lines.append(f"| `{relative}` | {role} | {detail} |")
    lines += [
        "", "## 1. UCI SMS Spam Collection", "",
        f"- **File and format:** `sms+spam+collection/SMSSpamCollection`; headerless, UTF-8, tab-delimited. Shape: {uci_raw.shape}.",
        "- **Columns assigned while loading:** `label`, `text`. The first records are ham messages, confirming label then message ordering.",
        f"- **Original labels:** {_table(uci_raw['label'].value_counts().to_dict())}. Mapping verified from `readme`: `ham → 0` (legitimate), `spam → 1` (scam).",
        f"- **Missing values:** {_table(uci_raw.isna().sum().to_dict())}. **Exact duplicate messages:** {int(uci_raw.duplicated('text').sum())}.",
        f"- **Samples:** `{uci_raw.iloc[0]['label']}` / `{uci_raw.iloc[0]['text'][:100]}`; `{uci_raw.iloc[2]['label']}` / `{uci_raw.iloc[2]['text'][:100]}`.",
        "", "## 2. Mendeley SMS phishing dataset", "",
        f"- **File and format:** nested `Dataset_5971.zip` containing `Dataset_5971.csv`; UTF-8 CSV with header. Shape: {mendeley_raw.shape}.",
        f"- **Columns:** {', '.join('`'+c+'`' for c in mendeley_raw.columns)}. The message field is `TEXT`; label field is `LABEL`.",
        f"- **Original labels:** {_table(mendeley_raw['LABEL'].value_counts().to_dict())}. Mapping: `ham → 0`; case-insensitive `spam`, `smishing`, and `phishing → 1`.",
        f"- **Missing values in LABEL/TEXT:** {_table(mendeley_raw[['LABEL', 'TEXT']].isna().sum().to_dict())}. **Exact duplicate messages:** {int(mendeley_raw.duplicated('TEXT').sum())}.",
        f"- **Samples:** `{str(mendeley_raw.iloc[0]['LABEL'])}` / `{str(mendeley_raw.iloc[0]['TEXT'])[:100]}`; `{str(mendeley_raw.iloc[1]['LABEL'])}` / `{str(mendeley_raw.iloc[1]['TEXT'])[:100]}`.",
        "", "## 3. PhiUSIIL Phishing URL Dataset", "",
        f"- **File and format:** `phiusiil+phishing+url+dataset/PhiUSIIL_Phishing_URL_Dataset.csv`; UTF-8 with BOM, comma-delimited CSV with header. Shape: {url_raw.shape}.",
        f"- **Columns:** {', '.join('`'+c+'`' for c in url_raw.columns)}.",
        "- **Application-safe fields:** `URL` is the raw URL and `label` is the label. All other columns are deliberately excluded from the URL model because many are webpage-derived.",
        f"- **Original label distribution:** {_table(url_raw['label'].value_counts().to_dict())}. PhiUSIIL convention is `1 = legitimate`, `0 = phishing`; ScaMail mapping is deliberately inverted to `0 = legitimate`, `1 = phishing`.",
        f"- **Missing values:** URL: {int(url_raw['URL'].isna().sum())}; label: {int(url_raw['label'].isna().sum())}; all columns: {int(url_raw.isna().sum().sum())}. **Exact duplicate URLs:** {int(url_raw.duplicated('URL').sum())}.",
        f"- **Samples:** `{url_raw.iloc[0]['URL']}` (original label {url_raw.iloc[0]['label']}); `{url_raw.iloc[1]['URL']}` (original label {url_raw.iloc[1]['label']}).",
        "", "## Verification conclusion", "",
        "All required message/URL and label columns are unambiguous. The loader validates label values and fails loudly if a later dataset revision introduces an unknown label. The Mendeley ZIP is read in place, and no URL is opened or requested.",
    ]
    destination.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return destination


if __name__ == "__main__":
    print(build_dataset_report())
